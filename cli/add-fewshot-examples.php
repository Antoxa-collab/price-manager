<?php
/**
 * CLI скрипт для добавления few-shot примеров для WB промптов
 * Запуск: docker exec price-manager-php php /var/www/html/cli/add-fewshot-examples.php
 */

require_once dirname(__DIR__) . '/app/config.php';

echo "=== Добавление few-shot примеров для WB промптов ===\n\n";

try {
    $db = Database::getInstance();

    // Получаем ID промптов WB
    $prompts = $db->fetchAll(
        "SELECT id, name FROM ai_prompts WHERE marketplace = 'wildberries' AND is_active = 1"
    );

    echo "Найдено WB промптов: " . count($prompts) . "\n";
    foreach ($prompts as $p) {
        echo "  ID={$p['id']}: {$p['name']}\n";
    }
    echo "\n";

    // Примеры для каждого типа промпта
    $examples = [
        // Ответ на положительный отзыв (обычно ID=5 или ищем по имени)
        'Ответ на положительный отзыв WB' => [
            [
                'input' => 'Отзыв: Отличная фанера, ровная, без сучков. Использовал для полок в гараже - идеально подошла. Буду заказывать ещё!',
                'output' => 'Благодарим за отзыв! Рады, что фанера подошла для ваших полок. Будем рады видеть вас снова!'
            ],
            [
                'input' => 'Отзыв: Хорошее качество за эту цену. Доставили быстро, упаковано надёжно.',
                'output' => 'Спасибо за оценку! Стараемся поддерживать баланс качества и цены. Надёжная упаковка — наш приоритет при доставке.'
            ],
            [
                'input' => 'Отзыв: Супер! Заказываю уже третий раз, всегда отличное качество.',
                'output' => 'Благодарим за доверие и постоянство! Приятно, что качество соответствует вашим ожиданиям.'
            ]
        ],

        // Ответ на негативный отзыв
        'Ответ на негативный отзыв WB' => [
            [
                'input' => 'Отзыв: Пришла фанера с трещиной на углу. Очень расстроен, пришлось отпиливать часть.',
                'output' => 'Приносим извинения за доставленное неудобство. Повреждение могло произойти при транспортировке. Пожалуйста, свяжитесь с нами — поможем решить вопрос.'
            ],
            [
                'input' => 'Отзыв: Размеры не соответствуют заявленным, на 2 см меньше.',
                'output' => 'Благодарим за обратную связь. Допуск по ГОСТ составляет ±3мм. Если расхождение больше — готовы рассмотреть замену. Напишите нам для уточнения.'
            ]
        ],

        // Ответ на нейтральный отзыв
        'Ответ на нейтральный отзыв WB' => [
            [
                'input' => 'Отзыв: Нормальная фанера, ничего особенного. Для дачи сойдёт.',
                'output' => 'Спасибо за отзыв! Рады, что товар подошёл для ваших задач.'
            ],
            [
                'input' => 'Отзыв: Качество среднее, но за такую цену ожидал большего.',
                'output' => 'Благодарим за обратную связь. Учтём ваше мнение. Если есть конкретные пожелания — будем рады услышать.'
            ]
        ],

        // Ответ на вопрос
        'Ответ на вопрос WB' => [
            [
                'input' => 'Вопрос: Подойдёт ли эта фанера для пола в ванной комнате?',
                'output' => 'Для ванной рекомендуем влагостойкую фанеру марки ФСФ. Данный товар — марки ФК, подходит для сухих помещений. Посмотрите раздел "Влагостойкая фанера" в нашем каталоге.'
            ],
            [
                'input' => 'Вопрос: Какой максимальный вес выдерживает полка из этой фанеры?',
                'output' => 'Несущая способность зависит от толщины и пролёта полки. Фанера 18мм при пролёте 60см выдерживает до 30кг. Для больших нагрузок рекомендуем увеличить толщину или добавить рёбра жёсткости.'
            ],
            [
                'input' => 'Вопрос: Есть ли у вас фанера толщиной 6мм?',
                'output' => 'Да, фанера 6мм есть в наличии. Найдите её в нашем каталоге по фильтру "толщина". Если нужна помощь с выбором — напишите.'
            ]
        ]
    ];

    $inserted = 0;
    $skipped = 0;

    foreach ($prompts as $prompt) {
        $promptName = $prompt['name'];
        $promptId = $prompt['id'];

        if (!isset($examples[$promptName])) {
            echo "Пропуск: нет примеров для '{$promptName}'\n";
            continue;
        }

        echo "\nДобавляем примеры для '{$promptName}' (ID={$promptId})...\n";

        foreach ($examples[$promptName] as $example) {
            // Проверяем, не существует ли уже такой пример
            $existing = $db->fetchOne(
                "SELECT id FROM ai_examples WHERE prompt_id = ? AND input_text = ?",
                [$promptId, $example['input']]
            );

            if ($existing) {
                echo "  - Пропуск (уже существует): " . mb_substr($example['input'], 0, 50) . "...\n";
                $skipped++;
                continue;
            }

            $db->execute(
                "INSERT INTO ai_examples (prompt_id, input_text, output_text, is_active, created_at)
                 VALUES (?, ?, ?, 1, NOW())",
                [$promptId, $example['input'], $example['output']]
            );

            echo "  + Добавлен: " . mb_substr($example['input'], 0, 50) . "...\n";
            $inserted++;
        }
    }

    echo "\n=== РЕЗУЛЬТАТ ===\n";
    echo "Добавлено: {$inserted}\n";
    echo "Пропущено: {$skipped}\n";

    // Проверяем итог
    $count = $db->fetchColumn("SELECT COUNT(*) FROM ai_examples WHERE is_active = 1");
    echo "\nВсего активных примеров в БД: {$count}\n";

    // Показываем количество по промптам
    $stats = $db->fetchAll(
        "SELECT p.name, COUNT(e.id) as cnt
         FROM ai_prompts p
         LEFT JOIN ai_examples e ON e.prompt_id = p.id AND e.is_active = 1
         WHERE p.marketplace = 'wildberries'
         GROUP BY p.id, p.name"
    );

    echo "\nПримеров по промптам:\n";
    foreach ($stats as $s) {
        echo "  {$s['name']}: {$s['cnt']}\n";
    }

    echo "\n=== Готово ===\n";

} catch (Exception $e) {
    echo "ERROR: " . $e->getMessage() . "\n";
    exit(1);
}
